// After `vite build`: inline dist/index.html into api/_lib/shell.generated.ts so
// api/share never fetches its own origin (preview deploys return 401 behind
// Deployment Protection; eng review OV-6).
import { readFileSync, writeFileSync } from "node:fs";

const html = readFileSync(new URL("../dist/index.html", import.meta.url), "utf8");
if (!html.includes("<!--OG-->")) throw new Error("dist/index.html lost the <!--OG--> marker");
writeFileSync(
  new URL("../api/_lib/shell.generated.ts", import.meta.url),
  `// GENERATED by scripts/inline-index.mjs from dist/index.html. Do not edit.\nexport const SHELL = ${JSON.stringify(html)};\n`,
);
console.log("api/_lib/shell.generated.ts updated");
